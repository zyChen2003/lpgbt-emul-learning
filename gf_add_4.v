// GF(2^4)加法
// 伽罗瓦域GF(2^4)上的加法运算
module gf_add_4(op1, op2, res);

// -------------------------------------------------------------------------- //
// ------------- Triple Modular Redundancy Generator Directives ------------- //
// -------------------------------------------------------------------------- //
// tmrg do_not_touch
// -------------------------------------------------------------------------- //

	input      [3:0] op1; 
	input      [3:0] op2; 
	output     [3:0] res;

	assign res = op1 ^ op2;

endmodule
